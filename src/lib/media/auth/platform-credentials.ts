/**
 * 跨模块平台凭证壳（音乐 + 影视共用）
 * 基于现有 audio auth session 存储，增加 headers / yt-dlp 导出。
 */

import {
  clearAuthSession,
  cookiesFromManualInput,
  checkAuthHealth,
  loadAuthSession,
  openPlatformLogin,
  persistAuthCookies,
  persistNeteaseQrCookies,
  persistBiliQrCookies,
  type PlatformId,
  getPlatformLoginUrl,
} from '@/lib/media/audio/platform/auth/session';
import type { AudioAuthSession } from '@/lib/media/audio/track-types';

export type { PlatformId };
export {
  clearAuthSession,
  cookiesFromManualInput,
  checkAuthHealth,
  loadAuthSession,
  openPlatformLogin,
  persistAuthCookies,
  persistNeteaseQrCookies,
  persistBiliQrCookies,
  getPlatformLoginUrl,
};

export type PlatformCredential = {
  platform: PlatformId | string;
  cookies: string;
  headers: Record<string, string>;
  updatedAt: number;
  healthy: boolean;
  expiresAt?: number;
};

const EXTRA_HEADERS_KEY = 'reader_media_platform_headers_v1';

function readHeaderStore(): Record<string, Record<string, string>> {
  try {
    const raw = localStorage.getItem(EXTRA_HEADERS_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw) as Record<string, Record<string, string>>;
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

function writeHeaderStore(store: Record<string, Record<string, string>>): void {
  try {
    localStorage.setItem(EXTRA_HEADERS_KEY, JSON.stringify(store));
  } catch {
    // ignore
  }
}

export async function getPlatformCredential(
  platform: PlatformId | string,
): Promise<PlatformCredential | null> {
  const session = await loadAuthSession(platform as PlatformId);
  if (!session?.cookies?.trim()) return null;
  const headers = readHeaderStore()[platform] ?? {};
  return {
    platform,
    cookies: session.cookies,
    headers,
    updatedAt: session.updatedAt,
    healthy: session.healthy,
  };
}

export async function setPlatformCredential(input: {
  platform: PlatformId | string;
  cookies: string;
  headers?: Record<string, string>;
  healthy?: boolean;
}): Promise<void> {
  await persistAuthCookies(
    input.platform as PlatformId,
    cookiesFromManualInput(input.cookies),
    input.healthy !== false,
  );
  if (input.headers) {
    const store = readHeaderStore();
    store[input.platform] = { ...input.headers };
    writeHeaderStore(store);
  }
}

/** 供 fetch / 播放代理使用 */
export function toRequestHeaders(cred: PlatformCredential | null | undefined): Record<string, string> {
  if (!cred?.cookies?.trim()) return { ...(cred?.headers ?? {}) };
  return {
    ...(cred.headers ?? {}),
    Cookie: cred.cookies,
  };
}

/**
 * Netscape cookie 文件正文，供后续 yt-dlp `--cookies` 使用。
 * 不写盘；调用方决定落盘路径。
 */
export function toYtDlpCookiesFile(cred: PlatformCredential | null | undefined): string {
  if (!cred?.cookies?.trim()) return '';
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Reader platform-credentials'];
  const parts = cred.cookies.split(';').map((s) => s.trim()).filter(Boolean);
  const domainGuess =
    cred.platform === 'bili'
      ? '.bilibili.com'
      : cred.platform === 'ytm'
        ? '.youtube.com'
        : '.music.163.com';
  for (const part of parts) {
    const eq = part.indexOf('=');
    if (eq <= 0) continue;
    const name = part.slice(0, eq).trim();
    const value = part.slice(eq + 1).trim();
    // domain \t includeSub \t path \t secure \t expiry \t name \t value
    lines.push(`${domainGuess}\tTRUE\t/\tFALSE\t0\t${name}\t${value}`);
  }
  return lines.join('\n');
}

export async function listPlatformCredentials(): Promise<PlatformCredential[]> {
  const platforms: PlatformId[] = ['netease', 'bili', 'ytm'];
  const out: PlatformCredential[] = [];
  for (const p of platforms) {
    const c = await getPlatformCredential(p);
    if (c) out.push(c);
  }
  return out;
}

export async function sessionToCredential(
  session: AudioAuthSession,
): Promise<PlatformCredential> {
  const headers = readHeaderStore()[session.platform] ?? {};
  return {
    platform: session.platform,
    cookies: session.cookies,
    headers,
    updatedAt: session.updatedAt,
    healthy: session.healthy,
  };
}
